// Creates demo Ed25519 keypairs (if missing) and writes the public keys to
// shared/keys.js. Names and IDs convey no agency or venue authority.
//
//   node scripts/genkeys.mjs
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const nacl = require('../vendor/nacl-fast.min.js');
const root = new URL('..', import.meta.url).pathname;

const AGENCIES = [
  { id: 'la-county-oem', name: 'CHIRP TEST key 1 (no LA County authority)' },
  { id: 'coliseum-ops', name: 'CHIRP venue TEST key (no venue authority)' },
];

const b64 = (bytes) => Buffer.from(bytes).toString('base64');
mkdirSync(`${root}keys`, { recursive: true });

const trusted = AGENCIES.map(({ id, name }) => {
  const file = `${root}keys/${id}.secret`;
  if (!existsSync(file)) {
    writeFileSync(file, b64(nacl.sign.keyPair().secretKey) + '\n');
    console.log(`created ${file}`);
  }
  const secret = Buffer.from(readFileSync(file, 'utf8').trim(), 'base64');
  return { id, name, publicKey: b64(nacl.sign.keyPair.fromSecretKey(secret).publicKey) };
});

writeFileSync(
  `${root}shared/keys.js`,
    `// Generated by scripts/genkeys.mjs. Demo public keys; no agency or venue authority.\n` +
    `export const TRUSTED_KEYS = ${JSON.stringify(trusted, null, 2)};\n`,
);
console.log('wrote shared/keys.js');
