// Creates a demo Ed25519 keypair for each agency (if missing) and writes the
// public keys to shared/keys.js. Secret keys stay in keys/ (gitignored).
//
//   node scripts/genkeys.mjs
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const nacl = require('../vendor/nacl-fast.min.js');
const root = new URL('..', import.meta.url).pathname;

const AGENCIES = [
  { id: 'la-county-oem', name: 'LA County Emergency Management (demo key)' },
  { id: 'coliseum-ops', name: 'LA Memorial Coliseum Event Ops (demo key)' },
];

const b64 = (bytes) => Buffer.from(bytes).toString('base64');
mkdirSync(`${root}keys`, { recursive: true });

const trusted = AGENCIES.map(({ id, name }) => {
  const file = `${root}keys/${id}.secret`;
  if (!existsSync(file)) {
    writeFileSync(file, b64(nacl.sign.keyPair().secretKey) + '\n');
    console.log(`created ${file}`);
  }
  const secret = Buffer.from(readFileSync(file, 'utf8').trim(), 'base64');
  return { id, name, publicKey: b64(nacl.sign.keyPair.fromSecretKey(secret).publicKey) };
});

writeFileSync(
  `${root}shared/keys.js`,
  `// Generated by scripts/genkeys.mjs. Public keys of agencies phones trust.\n` +
    `export const TRUSTED_KEYS = ${JSON.stringify(trusted, null, 2)};\n`,
);
console.log('wrote shared/keys.js');
